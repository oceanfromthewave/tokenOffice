// Generates sprites.css: 16x23 pixel-art office workers, two frames each (typing / walking).
// Run: node tools/make-sprites.mjs
import { writeFileSync } from 'node:fs';

const W = 16, H = 23;
const OUTLINE = '#241c33';
const shared = { k: '#241c33', w: '#ffffff', c: '#ff8f9c', b: '#f4f6ff', p: '#3b4272', h: '#1d2140' };
const animals = {
  momo: { species: 'bear',   f: '#c58b5a', g: '#a06a40', l: '#ecd3a8', e: '#8a5a36', s: '#6f94ff', t: '#4c6fd6' },
  lumi: { species: 'rabbit', f: '#f4f1f7', g: '#cdc8e0', l: '#ffffff', e: '#f4a6b9', s: '#ff82a8', t: '#d95f85' },
  tori: { species: 'pig',    f: '#f6b6bf', g: '#dd8d9b', l: '#f6b6bf', e: '#ee8fa0', s: '#3fc1ae', t: '#2a9988' },
  koko: { species: 'cat',    f: '#f2a65a', g: '#d0813a', l: '#ffe2b8', e: '#ffb4ac', s: '#9b8cff', t: '#7766e0' },
};

function frame(species, [leftHand, rightHand]) {
  const g = Array.from({ length: H }, () => Array(W).fill('.'));
  const px = (x, y, c) => { g[y][x] = c; };
  const rect = (x, y, w, h, c) => { for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) px(x + i, y + j, c); };

  // ears go down first so the head overdraws their roots
  if (species === 'bear') { rect(2, 2, 3, 3, 'f'); rect(11, 2, 3, 3, 'f'); px(3, 3, 'e'); px(12, 3, 'e'); }
  if (species === 'rabbit') { rect(4, 0, 2, 5, 'f'); rect(10, 0, 2, 5, 'f'); rect(5, 1, 1, 3, 'e'); rect(10, 1, 1, 3, 'e'); }
  if (species === 'pig') { rect(2, 3, 3, 2, 'e'); rect(11, 3, 3, 2, 'e'); }
  if (species === 'cat') {
    for (const [x, y] of [[3, 2], [3, 3], [4, 3], [2, 4], [3, 4], [4, 4], [12, 2], [12, 3], [11, 3], [11, 4], [12, 4], [13, 4]]) px(x, y, 'f');
    px(4, 3, 'e'); px(11, 3, 'e');
  }

  // head
  rect(2, 4, 12, 10, 'f');
  for (const [x, y] of [[2, 4], [13, 4], [2, 13], [13, 13]]) px(x, y, '.');
  rect(3, 13, 10, 1, 'g'); rect(13, 5, 1, 8, 'g');
  px(3, 5, 'l'); px(4, 5, 'l'); px(3, 6, 'l');
  if (species === 'cat') { px(7, 5, 'g'); px(8, 5, 'g'); px(7, 6, 'g'); px(8, 6, 'g'); }

  // face
  rect(4, 7, 2, 3, 'k'); rect(10, 7, 2, 3, 'k'); px(4, 7, 'w'); px(10, 7, 'w');
  rect(3, 10, 2, 1, 'c'); rect(11, 10, 2, 1, 'c');
  if (species === 'pig') { rect(5, 10, 6, 3, 'e'); px(6, 11, 'k'); px(9, 11, 'k'); }
  else {
    rect(6, 10, 4, 3, 'l');
    if (species === 'bear') rect(7, 10, 2, 1, 'k');
    else rect(7, 10, 2, 1, 'e');
    px(7, 12, 'k'); px(8, 12, 'k');
  }

  // shirt, collar, badge
  rect(4, 14, 8, 6, 's'); rect(11, 14, 1, 6, 't'); rect(4, 19, 8, 1, 't');
  rect(6, 14, 4, 1, 'b'); px(9, 16, 'b'); px(9, 17, 'b');
  // arms: sleeves end in a fur-coloured hand; the two frames swap hand heights
  for (const [x, hand] of [[3, leftHand], [12, rightHand]]) { rect(x, 15, 1, hand - 15, 's'); px(x, hand, 'f'); }
  // legs
  rect(5, 20, 2, 2, 'p'); rect(9, 20, 2, 2, 'p'); rect(4, 22, 3, 1, 'h'); rect(9, 22, 3, 1, 'h');

  // 1px outline around everything
  const out = g.map(row => row.slice());
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    if (g[y][x] !== '.') continue;
    if ([[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => (g[y + dy]?.[x + dx] ?? '.') !== '.')) out[y][x] = 'o';
  }
  return out;
}

function sheet(look) {
  const a = animals[look];
  const colors = { ...shared, ...a, o: OUTLINE };
  const paths = {};
  [frame(a.species, [19, 18]), frame(a.species, [18, 19])].forEach((rows, n) => {
    rows.forEach((row, y) => {
      for (let x = 0; x < W;) {
        const c = row[x];
        if (c === '.') { x++; continue; }
        let run = 1;
        while (x + run < W && row[x + run] === c) run++;
        (paths[c] ||= []).push(`M${x + n * W} ${y}h${run}v1h-${run}z`);
        x += run;
      }
    });
  });
  const body = Object.entries(paths).map(([c, d]) => `<path fill='${colors[c]}' d='${d.join('')}'/>`).join('');
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${W * 2} ${H}' shape-rendering='crispEdges'>${body}</svg>`;
  return `.character[data-look="${look}"] { --sprite: url("data:image/svg+xml,${encodeURIComponent(svg)}"); }`;
}

const css = `/* generated by tools/make-sprites.mjs — do not edit by hand */\n${Object.keys(animals).map(sheet).join('\n')}\n`;
writeFileSync(new URL('../sprites.css', import.meta.url), css);
console.log(`sprites.css ${css.length} bytes`);
